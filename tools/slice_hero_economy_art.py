def find_gutter_splits(sheet_rgb: np.ndarray, count: int, axis: int) -> List[int]:
    """
    Finds optimal pure-white gutter split coordinates along `axis` (0=rows/y, 1=cols/x)
    within +/- 7% of each ideal 1/count boundary so protruding comic spikes/flames/wings
    are never clipped.
    """
    length = sheet_rgb.shape[axis]
    min_c = sheet_rgb.min(axis=2)
    sat = sheet_rgb.max(axis=2).astype(np.int16) - min_c.astype(np.int16)
    non_white = (min_c < 238) | (sat > 20)
    proj = non_white.sum(axis=(1 if axis == 0 else 0)).astype(np.float64)
    kernel = np.array([0.15, 0.2, 0.3, 0.2, 0.15])
    smooth = np.convolve(proj, kernel, mode="same")

    splits = [0]
    win = max(8, int(round(length * 0.07)))
    for k in range(1, count):
        ideal = int(round(k * length / float(count)))
        lo = max(1, ideal - win)
        hi = min(length - 1, ideal + win)
        segment = smooth[lo : hi + 1]
        min_val = segment.min()
        candidates = np.where(segment <= min_val + 0.5)[0] + lo
        best = int(candidates[np.argmin(np.abs(candidates - ideal))])
        splits.append(best)
    splits.append(length)
    return splits


def cutout_comic_icon_cell(
    cell_rgb: np.ndarray,
    hole_mode: str = "border",
    white_min: float = 236.0,
    sat_max: float = 22.0,
) -> Image.Image:
    """
    Cuts out a bold dark-ink comic icon from a solid white grid cell using strictly
    EXTERIOR border-connected white flood-fill so ALL interior whites (SOS/CALL text,
    hourglass glass reflections, red/white shield stripes, scope crosshairs, medic cross,
    book pages, and skull/star highlights) remain 100% opaque!
    """
    sub = cell_rgb.copy()
    h, w, _ = sub.shape

    # Trim 2px outermost cell edge in case adjacent cell ink grazed a split line, then pad 4px pure white
    pad = np.full((h + 8, w + 8, 3), 255, dtype=np.uint8)
    pad[4 : 4 + h, 4 : 4 + w] = sub

    rgb_f = pad.astype(np.float32)
    min_c = rgb_f.min(axis=2)
    max_c = rgb_f.max(axis=2)
    sat = max_c - min_c

    bg_cand = (min_c >= white_min) & (sat <= sat_max)
    if hole_mode == "warm_glow":
        # Flood-fill pale cream/amber paper glow strictly OUTSIDE the continuous dark brown/charcoal
        # comic outline (`g < 140` on the outline completely blocks entry into interior crystal facets!)
        r_p, g_p, b_p = rgb_f[:, :, 0], rgb_f[:, :, 1], rgb_f[:, :, 2]
        pale_aura = (r_p >= 232.0) & (g_p >= 184.0) & (b_p >= 105.0)
        bg_cand = bg_cand | pale_aura

    labeled, _ = ndimage.label(bg_cand)
    ext_label = labeled[0, 0]
    bg_mask = (labeled == ext_label)[4 : 4 + h, 4 : 4 + w]

    sub_f = sub.astype(np.float32)
    s_min = sub_f.min(axis=2)
    s_sat = sub_f.max(axis=2) - s_min

    fg = ~bg_mask
    # Keep the main icon + any genuine comic sparks/stars (>= 18 px), drop tiny JPEG dust
    comp, n_comp = ndimage.label(fg)
    if n_comp > 0:
        sizes = ndimage.sum(fg, comp, range(1, n_comp + 1))
        max_sz = max(sizes) if len(sizes) > 0 else 0
        for cid, sz in enumerate(sizes, start=1):
            if sz < 18:
                fg[comp == cid] = False
                continue
            # Drop stray corner slivers from neighbor cells if tiny and touching cell border
            if sz < max_sz * 0.04:
                ys_c, xs_c = np.where(comp == cid)
                touches_edge = (
                    ys_c.min() <= 1 or ys_c.max() >= h - 2 or xs_c.min() <= 1 or xs_c.max() >= w - 2
                )
                if touches_edge:
                    fg[comp == cid] = False

    # Surgical enclosed pure-#FFFFFF background hole cutouts
    if hole_mode in ("pure_holes", "hourglass_pillars", "gear_loops"):
        fg_ys, fg_xs = np.where(fg)
        if len(fg_ys) > 0:
            fy0, fy1 = int(fg_ys.min()), int(fg_ys.max())
            fx0, fx1 = int(fg_xs.min()), int(fg_xs.max())
            fh = max(1, fy1 - fy0 + 1)
            fw = max(1, fx1 - fx0 + 1)
            fcy = 0.5 * (fy0 + fy1)
            fcx = 0.5 * (fx0 + fx1)
            frad = 0.24 * min(fh, fw)

            w_thr = 240.0 if hole_mode in ("hourglass_pillars", "gear_loops") else 246.0
            s_thr = 14.0 if hole_mode in ("hourglass_pillars", "gear_loops") else 10.0
            pure_white = (s_min >= w_thr) & (s_sat <= s_thr) & fg
            hl_lbl, n_hl = ndimage.label(pure_white)
            for lid in range(1, n_hl + 1):
                ys_h, xs_h = np.where(hl_lbl == lid)
                if len(ys_h) < 14:
                    continue
                mx = float(xs_h.mean())
                my = float(ys_h.mean())
                if hole_mode == "hourglass_pillars":
                    # Punch ONLY the 2 large enclosed background gaps (>= 800 px) between the narrow glass
                    # waist and the left/right brass rods, keeping 100% of the glass sheen reflections!
                    if len(ys_h) < 800:
                        continue
                elif hole_mode == "pure_holes":
                    if math.hypot(mx - fcx, my - fcy) <= frad:
                        continue
                # Note: in `gear_loops` (weapon stock/trigger, boots piston slot, goggles strap oval),
                # none of the steel/leather/green-visor artwork is pure neutral white, so all >=14px
                # pure-white enclosed loops are genuine background cutouts!
                hole_region = ndimage.binary_dilation(hl_lbl == lid, iterations=1) & (s_min >= 205.0) & (s_sat <= 24.0)
                fg[hole_region] = False

    # Anti-aliased comic ink edge + white/cream halo decontamination toward #171B2E
    dist_in = ndimage.distance_transform_edt(fg)
    alpha = np.where(fg, 1.0, 0.0).astype(np.float32)

    sat_lim = 135.0 if hole_mode == "warm_glow" else 28.0
    min_lim = 155.0 if hole_mode == "warm_glow" else 190.0
    fringe = fg & (dist_in <= 2.4) & (s_min > min_lim) & (s_sat < sat_lim)
    whiteness = np.clip((s_min - 150.0) / 95.0, 0.0, 1.0)
    alpha[fringe] = np.minimum(alpha[fringe], 1.0 - whiteness[fringe] * 0.94)

    edge_ring = fg & (dist_in <= 1.9) & (s_min > 155.0) & (s_sat < sat_lim)
    sub_f[edge_ring, 0] = sub_f[edge_ring, 0] * 0.25 + 23.0 * 0.75
    sub_f[edge_ring, 1] = sub_f[edge_ring, 1] * 0.25 + 27.0 * 0.75
    sub_f[edge_ring, 2] = sub_f[edge_ring, 2] * 0.25 + 46.0 * 0.75

    rgba = np.zeros((h, w, 4), dtype=np.uint8)
    rgba[:, :, :3] = np.clip(sub_f, 0, 255).astype(np.uint8)
    rgba[:, :, 3] = np.clip(alpha * 255.0, 0, 255).astype(np.uint8)

    ys, xs = np.where(rgba[:, :, 3] > 16)
    if len(xs) == 0:
        return Image.fromarray(rgba, "RGBA")

    pad_px = 4
    x0, x1 = max(0, int(xs.min()) - pad_px), min(w, int(xs.max()) + 1 + pad_px)
    y0, y1 = max(0, int(ys.min()) - pad_px), min(h, int(ys.max()) + 1 + pad_px)
    return Image.fromarray(rgba[y0:y1, x0:x1], "RGBA")


def fit_icon_square(im: Image.Image, size: int = ICON_SIZE, margin: int = 8) -> Image.Image:
    avail = max(16, size - margin * 2)
    w, h = im.size
    scale = min(avail / float(w), avail / float(h))
    nw = max(1, int(round(w * scale)))
    nh = max(1, int(round(h * scale)))
    resized = im.resize((nw, nh), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(resized, ((size - nw) // 2, (size - nh) // 2))
    return canvas


def process_icon_sheet(
    sheet_label: str,
    src_path: Path,
    specs: Sequence[Tuple[int, int, str, str]],
    used_guids: Set[str],
) -> List[Tuple[str, Image.Image]]:
    if not src_path.is_file():
        raise FileNotFoundError(f"[{sheet_label}] Raw sheet not found: {src_path}")

    sheet = np.array(Image.open(src_path).convert("RGB"))
    y_splits = find_gutter_splits(sheet, 3, axis=0)
    x_splits = find_gutter_splits(sheet, 3, axis=1)
    print(f"[{sheet_label}] Loaded {src_path} ({sheet.shape[1]}x{sheet.shape[0]}), splits x={x_splits}, y={y_splits}")

    saved: List[Tuple[str, Image.Image]] = []
    for r, c, name, hmode in specs:
        cell = sheet[y_splits[r] : y_splits[r + 1], x_splits[c] : x_splits[c + 1]].copy()
        cut = cutout_comic_icon_cell(cell, hole_mode=hmode)
        out_im = fit_icon_square(cut, size=ICON_SIZE, margin=8)
        out_path = OUT_DIR / f"{name}.png"
        out_im.save(out_path, format="PNG", optimize=True)
        write_icon_sprite_meta(out_path, used_guids=used_guids, max_tex_size=512)
        print(f"[{sheet_label}] ({r},{c}) -> {out_path.name} ({out_im.size}, crop={cut.size})")
        saved.append((name, out_im))
    return saved


def save_contact_preview(items: Sequence[Tuple[str, Image.Image]], out_path: Path, cols: int = 3) -> None:
    if not items:
        return
    rows = (len(items) + cols - 1) // cols
    # Dual-background cell: left half dark slate (#1B2036), right half warm orange/lilac card (#F0A854 / #D8DCF2)
    cell_w, cell_h = 228, 240
    preview = Image.new("RGBA", (cols * cell_w, rows * cell_h), (24, 28, 46, 255))
    draw = ImageDraw.Draw(preview)
    for idx, (name, im) in enumerate(items):
        r, c = divmod(idx, cols)
        ox, oy = c * cell_w, r * cell_h
        mid_x = ox + cell_w // 2
        right_bg = (242, 165, 78, 255) if (r + c) % 2 == 0 else (196, 128, 242, 255)
        draw.rectangle([ox + 3, oy + 3, mid_x, oy + cell_h - 4], fill=(26, 31, 52, 255))
        draw.rectangle([mid_x, oy + 3, ox + cell_w - 4, oy + cell_h - 4], fill=right_bg)
        draw.rectangle([ox + 3, oy + 3, ox + cell_w - 4, oy + cell_h - 4], outline=(72, 82, 118, 255), width=2)
        ix = ox + (cell_w - im.width) // 2
        iy = oy + 10 + (ICON_SIZE - im.height) // 2
        preview.alpha_composite(im, (ix, iy))
        draw.rectangle([ox + 4, oy + cell_h - 26, ox + cell_w - 5, oy + cell_h - 5], fill=(18, 22, 36, 225))
        draw.text((ox + 10, oy + cell_h - 22), name, fill=(240, 244, 255, 255))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    preview.save(out_path, format="PNG")
    print(f"[Preview] Wrote dual-bg contact sheet: {out_path}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Slice Hero Economy sheets E1..E3 and compose 6 Hero Jigsaw Shards.")
    parser.add_argument("--shards", action="store_true", help="Compose the 6 Hero Jigsaw Shard PNGs from bust_*.png")
    parser.add_argument("--e1", type=str, default="", help="Path to raw 3x3 Sheet E1 image")
    parser.add_argument("--e2", type=str, default="", help="Path to raw 3x3 Sheet E2 image")
    parser.add_argument("--e3", type=str, default="", help="Path to raw 3x3 Sheet E3 image")
    parser.add_argument("--preview-dir", type=str, default="", help="Optional directory to emit contact sheet PNGs")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    used_guids = collect_existing_guids(ASSETS_ROOT)
    preview_dir = Path(args.preview_dir) if args.preview_dir else None

    ran_any = False
    if args.shards:
        ran_any = True
        shards = compose_hero_shards(used_guids)
        if preview_dir:
            save_contact_preview(shards, preview_dir / "preview_shards.png", cols=3)

    if args.e1:
        ran_any = True
        e1_items = process_icon_sheet("E1", Path(args.e1), SHEET_E1_SPECS, used_guids)
        if preview_dir:
            save_contact_preview(e1_items, preview_dir / "preview_e1.png", cols=3)

    if args.e2:
        ran_any = True
        e2_items = process_icon_sheet("E2", Path(args.e2), SHEET_E2_SPECS, used_guids)
        if preview_dir:
            save_contact_preview(e2_items, preview_dir / "preview_e2.png", cols=3)

    if args.e3:
        ran_any = True
        e3_items = process_icon_sheet("E3", Path(args.e3), SHEET_E3_SPECS, used_guids)
        if preview_dir:
            save_contact_preview(e3_items, preview_dir / "preview_e3.png", cols=3)

    if not ran_any:
        parser.print_help()
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
