def _build_interlocking_jigsaw_mask(ss_size: int, tilt_deg: float = -14.0) -> np.ndarray:
    """
    Constructs a smooth, authentic interlocking jigsaw puzzle piece binary mask at `ss_size`
    (e.g. 768x768 for 4x supersampling -> 192x192):
      - Rounded-corner square body rotated `tilt_deg` (-14 deg CCW, matching Water-World shards)
      - 3 outward interlocking puzzle knobs (Top, Right, Bottom) with narrow neck + bulbous head
      - 1 inward interlocking puzzle socket (Left) so eyes/nose/mouth stay 100% unobstructed!
    """
    yy, xx = np.mgrid[0:ss_size, 0:ss_size].astype(np.float32)
    # Shift center slightly left-down (-12, +8 at 768) so the 3 outward knobs (Top, Right, Bottom)
    # and 1 inward socket (Left) sit optically dead-center on the 192x192 canvas!
    scale = ss_size / 192.0
    cx = ss_size * 0.5 - 3.5 * scale
    cy = ss_size * 0.5 + 2.0 * scale

    dx = xx - cx
    dy = yy - cy
    theta = math.radians(-tilt_deg)  # inverse rotate coordinates into local puzzle space
    cos_t = math.cos(theta)
    sin_t = math.sin(theta)
    lx = dx * cos_t - dy * sin_t
    ly = dx * sin_t + dy * cos_t

    half = 47.0 * scale
    corner_r = 7.5 * scale

    # Signed distance to rounded box [-half, +half]^2
    qx = np.abs(lx) - (half - corner_r)
    qy = np.abs(ly) - (half - corner_r)
    outside_d = np.hypot(np.maximum(qx, 0.0), np.maximum(qy, 0.0))
    inside_d = np.minimum(np.maximum(qx, qy), 0.0)
    sd_box = outside_d + inside_d - corner_r
    mask = sd_box <= 0.0

    knob_r = 14.2 * scale
    knob_offset = 10.8 * scale  # distance of knob circle center outside the box edge
    neck_half_w = 8.8 * scale
    neck_depth = 12.0 * scale

    def add_outward_tab(tx: np.ndarray, ty: np.ndarray) -> np.ndarray:
        """Outward tab along +ty from edge ty = +half."""
        head = (tx ** 2 + (ty - (half + knob_offset)) ** 2) <= (knob_r ** 2)
        neck = (np.abs(tx) <= neck_half_w) & (ty >= half - 4.0 * scale) & (ty <= half + knob_offset)
        return head | neck

    def make_inward_socket(tx: np.ndarray, ty: np.ndarray) -> np.ndarray:
        """Inward socket along -ty into edge ty = +half (mirrored via coords)."""
        head = (tx ** 2 + (ty - (half - knob_offset * 0.92)) ** 2) <= ((knob_r * 0.92) ** 2)
        neck = (np.abs(tx) <= (neck_half_w * 0.90)) & (ty >= half - knob_offset * 0.92) & (ty <= half + 4.0 * scale)
        return head | neck

    # Top edge (ly = -half -> outward is -ly, so pass ty = -ly)
    mask |= add_outward_tab(lx, -ly)
    # Right edge (lx = +half -> outward is +lx, so pass tx = ly, ty = lx)
    mask |= add_outward_tab(ly, lx)
    # Bottom edge (ly = +half -> outward is +ly, so pass tx = lx, ty = ly)
    mask |= add_outward_tab(lx, ly)
    # Left edge (lx = -half -> inward socket into lx = -half, so pass tx = ly, ty = -lx)
    socket_left = make_inward_socket(ly, -lx)
    mask &= ~socket_left

    # Light morphological closing + opening to smooth neck-to-body fillets cleanly
    smooth_r = max(2, int(round(3.0 * scale)))
    yy_k, xx_k = np.ogrid[-smooth_r : smooth_r + 1, -smooth_r : smooth_r + 1]
    disk = (xx_k ** 2 + yy_k ** 2) <= (smooth_r ** 2)
    mask = ndimage.binary_closing(mask, structure=disk)
    mask = ndimage.binary_opening(mask, structure=disk)
    return mask


def compose_hero_shards(used_guids: Set[str]) -> List[Tuple[str, Image.Image]]:
    """
    Generates and writes all 6 `ico_shard_<hero>.png` + `.png.meta` files at `192x192` RGBA:
      - 4x supersampled (`768x768`) anti-aliased jigsaw mask
      - Inner portrait masked cleanly to the jigsaw piece over a pale comic tile backdrop
      - Thin `1.5px` `#1E2442` inner ink contour framing the portrait
      - Crisp `5px` `#FFFFFF` white sticker rim
      - Bold `4px` `#171B2E` black comic ink outer outline + `2px` bottom-left comic tile depth
    """
    ss = 4
    ss_size = ICON_SIZE * ss  # 768x768
    inner_mask = _build_interlocking_jigsaw_mask(ss_size, tilt_deg=-14.0)

    # Signed Euclidean distance outside `inner_mask` (in supersampled pixels)
    dist_out = ndimage.distance_transform_edt(~inner_mask)
    dist_in = ndimage.distance_transform_edt(inner_mask)

    white_px = 5.0 * ss    # 5px white sticker border at 192x192
    ink_px = 4.0 * ss      # 4px #171B2E comic ink outer outline at 192x192
    inner_line_px = 1.4 * ss

    white_zone = (~inner_mask) & (dist_out <= white_px)
    ink_main = (~inner_mask) & (dist_out <= (white_px + ink_px))

    # Add subtle 3D die-cut comic thickness (-4px X, +6px Y in 768px = -1px X, +1.5px Y at 192px)
    extrude_base = ndimage.shift(ink_main.astype(np.uint8), shift=(6, -5), order=0) > 0
    full_silhouette = ink_main | extrude_base

    saved: List[Tuple[str, Image.Image]] = []
    yy, xx = np.mgrid[0:ss_size, 0:ss_size].astype(np.float32)

    for bust_fn, out_name, (cx0, cy0, cx1, cy1), bg_rgb in HERO_SHARD_SPECS:
        bust_path = OUT_DIR / bust_fn
        if not bust_path.is_file():
            raise FileNotFoundError(f"Missing hero portrait: {bust_path}")

        bust = Image.open(bust_path).convert("RGBA")
        bw, bh = bust.size
        # Crop with safe clamping / transparent padding if needed
        crop_side_w = cx1 - cx0
        crop_side_h = cy1 - cy0
        crop_canvas = Image.new("RGBA", (crop_side_w, crop_side_h), (0, 0, 0, 0))
        sx0 = max(0, cx0)
        sy0 = max(0, cy0)
        sx1 = min(bw, cx1)
        sy1 = min(bh, cy1)
        crop_canvas.paste(bust.crop((sx0, sy0, sx1, sy1)), (sx0 - cx0, sy0 - cy0))

        # Fit portrait head inside the jigsaw bounds (`~540x540` centered inside 768x768)
        target_port_sz = int(round(138 * ss))
        port_resized = crop_canvas.resize((target_port_sz, target_port_sz), Image.Resampling.LANCZOS)
        port_layer = Image.new("RGBA", (ss_size, ss_size), (0, 0, 0, 0))
        pox = (ss_size - target_port_sz) // 2 - int(2 * ss)
        poy = (ss_size - target_port_sz) // 2 + int(2 * ss)
        port_layer.alpha_composite(port_resized, (pox, poy))
        port_arr = np.array(port_layer, dtype=np.float32)

        # Build supersampled RGBA canvas
        canvas = np.zeros((ss_size, ss_size, 4), dtype=np.uint8)

        # Layer 1: Outer dark comic ink (#171B2E) including 3D bottom-left edge thickness
        canvas[full_silhouette] = (23, 27, 46, 255)

        # Layer 2: Crisp pure white sticker rim (#FFFFFF)
        canvas[white_zone] = (255, 255, 255, 255)

        # Layer 3: Pale comic portrait backdrop inside `inner_mask` (with subtle top-left sheen band)
        sheen = ((xx * 0.75 + yy * 0.65) < ss_size * 0.66)
        bg_r, bg_g, bg_b = bg_rgb
        tile_rgb = np.empty((ss_size, ss_size, 3), dtype=np.float32)
        tile_rgb[:, :, 0] = np.where(sheen, min(255, bg_r + 12), bg_r)
        tile_rgb[:, :, 1] = np.where(sheen, min(255, bg_g + 11), bg_g)
        tile_rgb[:, :, 2] = np.where(sheen, min(255, bg_b + 6), bg_b)

        # Alpha-composite hero portrait over `tile_rgb` strictly inside `inner_mask`
        pa = (port_arr[:, :, 3:4] / 255.0)
        comp_rgb = port_arr[:, :, :3] * pa + tile_rgb * (1.0 - pa)

        # Subtle inner dark-indigo hairline right against the white sticker inner rim
        inner_hairline = inner_mask & (dist_in <= inner_line_px)
        comp_rgb[inner_hairline] = comp_rgb[inner_hairline] * 0.28 + np.array([23.0, 27.0, 46.0]) * 0.72

        canvas[inner_mask, :3] = np.clip(comp_rgb[inner_mask], 0, 255).astype(np.uint8)
        canvas[inner_mask, 3] = 255

        # Downsample 4x -> 192x192 with LANCZOS for silky-smooth anti-aliased edges
        out_im = Image.fromarray(canvas, "RGBA").resize((ICON_SIZE, ICON_SIZE), Image.Resampling.LANCZOS)
        out_path = OUT_DIR / f"{out_name}.png"
        out_im.save(out_path, format="PNG", optimize=True)
        write_icon_sprite_meta(out_path, used_guids=used_guids, max_tex_size=512)
        print(f"[Hero Shard] Saved {out_path.name} ({out_im.size}, RGBA)")
        saved.append((out_name, out_im))

    return saved


